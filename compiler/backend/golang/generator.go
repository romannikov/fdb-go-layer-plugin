func generateQueryByIndex(g Printer, msg ir.MessageSpec, idx ir.SecondaryIndexSpec, queryFields []ir.FieldSpec) {
	lowerName := strings.ToLower(msg.Name)
	joinedNames := JoinFieldNames(queryFields)
	hasMut := ir.HasMutationFields(msg)
	hasVS := ir.MsgHasVersionstampPK(msg)
	isPartialPrefix := len(queryFields) < len(idx.Fields)

	var idxPackArgs []string
	for _, f := range queryFields {
		idxPackArgs = append(idxPackArgs, PackField(f.GoName, f))
	}

	g.P("// Query", msg.Name, "By", joinedNames, " retrieves a paginated page of ", msg.Name, " entities by their ", joinedNames, " index.")
	g.P("func (r *", lowerName, "Repository) Query", msg.Name, "By", joinedNames, "(ctx context.Context, tr fdb.ReadTransaction, dir directory.DirectorySubspace, ", fieldParamDecls(queryFields), ", opts ", msg.Name, "PaginationOptions) (*", msg.Name, "PaginatedResult, error) {")
	g.P("	if err := ctx.Err(); err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P(`	typeID, err := r.store.GetTypeID("`, msg.Name, `")`)
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P()
	g.P("	result := &", msg.Name, "PaginatedResult{")
	g.P("		Items: make([]*", msg.Name, ", 0),")
	g.P("	}")
	g.P("	baseTpl := tuple.Tuple{typeID, fdblayer.IndexNamespace, ", idx.IndexID, ", ", strings.Join(idxPackArgs, ", "), "}")
	g.P("	indexKeyPrefix := dir.Pack(baseTpl)")
	g.P("	indexRange, err := fdb.PrefixRange(indexKeyPrefix)")
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	rangeBegin := indexRange.Begin")
	g.P("	rangeEnd := indexRange.End")
	g.P("	if len(opts.Begin) > 0 {")
	g.P("		cursorTpl := make(tuple.Tuple, len(baseTpl)+len(opts.Begin))")
	g.P("		copy(cursorTpl, baseTpl)")
	g.P("		for j, el := range opts.Begin {")
	g.P("			cursorTpl[len(baseTpl)+j] = fdblayer.NormalizeTupleElement(el)")
	g.P("		}")
	if hasVS {
		suffixIdxFields := len(idx.Fields) - len(queryFields)
		for j, f := range msg.PrimaryKeyFields {
			if f.IsVersionstamp {
				vsOffset := suffixIdxFields + j
				g.P("		if len(opts.Begin) > ", vsOffset, " {")
				g.P("			if rawVS, ok := opts.Begin[", vsOffset, "].([]byte); ok {")
				g.P("				cursorTpl[len(baseTpl)+", vsOffset, "] = fdblayer.BytesToVersionstamp(rawVS)")
				g.P("			}")
				g.P("		}")
			}
		}
	}
	g.P("		cursorKey := dir.Pack(cursorTpl)")
	g.P("		if opts.Reverse {")
	g.P("			cursorRange, err := fdb.PrefixRange(cursorKey)")
	g.P("			if err != nil {")
	g.P("				return nil, err")
	g.P("			}")
	g.P("			if string(cursorRange.End.FDBKey()) < string(rangeEnd.FDBKey()) {")
	g.P("				rangeEnd = cursorRange.End")
	g.P("			}")
	g.P("		} else if string(cursorKey) > string(rangeBegin.FDBKey()) {")
	g.P("			rangeBegin = cursorKey")
	g.P("		}")
	g.P("	}")
	g.P("	if string(rangeBegin.FDBKey()) >= string(rangeEnd.FDBKey()) {")
	g.P("		return result, nil")
	g.P("	}")
	g.P("	rangeOpts := fdb.RangeOptions{Reverse: opts.Reverse}")
	g.P("	if opts.Limit > 0 {")
	g.P("		rangeOpts.Limit = opts.Limit + 1")
	g.P("	}")
	g.P("	kvs := fdblayer.GetRange(tr, fdb.KeyRange{Begin: rangeBegin, End: rangeEnd}, rangeOpts).GetSliceOrPanic()")
	g.P("	pageLen := len(kvs)")
	g.P("	pkIndexStart := 3 + ", len(idx.Fields))
	cursorStartVar := "pkIndexStart"
	if isPartialPrefix {
		g.P("	cursorStart := 3 + ", len(queryFields))
		cursorStartVar = "cursorStart"
	}
	g.P("	if opts.Limit > 0 && pageLen > opts.Limit {")
	g.P("		nextTpl, err := dir.Unpack(kvs[opts.Limit].Key)")
	g.P("		if err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	g.P("		if len(nextTpl) > ", cursorStartVar, " {")
	g.P("			result.HasMore = true")
	g.P("			result.NextKey = nextTpl[", cursorStartVar, ":]")
	g.P("		}")
	g.P("		kvs = kvs[:opts.Limit]")
	g.P("	}")
	g.P("	futures := make([]fdb.FutureByteSlice, len(kvs))")
	if hasVS {
		g.P("	pkTuples := make([]tuple.Tuple, len(kvs))")
	}
	if hasMut {
		g.P("	fieldFutures := make([]fdblayer.RangeFuture, len(kvs))")
	}
	g.P("	for i, kv := range kvs {")
	g.P("		if err := ctx.Err(); err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	g.P("		tpl, err := dir.Unpack(kv.Key)")
	g.P("		if err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	g.P("		if len(tpl) <= pkIndexStart {")
	g.P("			continue")
	g.P("		}")
	g.P("		pkTuple := tpl[pkIndexStart:]")
	if hasVS {
		g.P("		pkTuples[i] = pkTuple")
	}
	g.P("		keyTpl := make(tuple.Tuple, 2+len(pkTuple))")
	g.P("		keyTpl[0] = typeID")
	g.P("		keyTpl[1] = fdblayer.DataNamespace")
	g.P("		copy(keyTpl[2:], pkTuple)")
	g.P("		futures[i] = tr.Get(dir.Pack(keyTpl))")
	if hasMut {
		g.P("		fieldTpl := make(tuple.Tuple, 2+len(pkTuple))")
		g.P("		fieldTpl[0] = typeID")
		g.P("		fieldTpl[1] = fdblayer.FieldNamespace")
		g.P("		copy(fieldTpl[2:], pkTuple)")
		g.P("		fieldRange, err := fdb.PrefixRange(dir.Pack(fieldTpl))")
		g.P("		if err != nil {")
		g.P("			return nil, err")
		g.P("		}")
		g.P("		fieldFutures[i] = fdblayer.GetRange(tr, fieldRange, fdb.RangeOptions{})")
	}
	g.P("	}")
	iterVar := "_"
	if hasMut || hasVS {
		iterVar = "i"
	}
	g.P("	for ", iterVar, ", future := range futures {")
	g.P("		if err := ctx.Err(); err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	g.P("		if future == nil {")
	g.P("			continue")
	g.P("		}")
	g.P("		value := future.MustGet()")
	g.P("		if value == nil {")
	g.P("			continue")
	g.P("		}")
	g.P("		entity := &", msg.Name, "{}")
	g.P("		if err := proto.Unmarshal(value, entity); err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	if hasVS {
		for j, f := range msg.PrimaryKeyFields {
			if f.IsVersionstamp {
				g.P("		if len(pkTuples[i]) > ", j, " {")
				g.P("			if vs, ok := pkTuples[i][", j, "].(tuple.Versionstamp); ok {")
				g.P("				entity.", f.GoName, " = vs.Bytes()")
				g.P("			}")
				g.P("		}")
			}
		}
	}
	if hasMut {
		generateUnmarshalAtomicFields(g, msg, "fieldFutures[i].GetSliceOrPanic()", "\t\t")
	}
	g.P("		result.Items = append(result.Items, entity)")
	g.P("	}")
	g.P("	return result, nil")
	g.P("}")
	g.P()
}

func generateAtomicMutators(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	var pkPackArgs []string
	for _, f := range msg.PrimaryKeyFields {
		pkPackArgs = append(pkPackArgs, PackField(f.GoName, f))
	}
	pkArgsStr := strings.Join(pkPackArgs, ", ")

	for _, f := range msg.Fields {
		if f.Mutation == ir.MutationNone {
			continue
		}
		verb := MutationVerb(f.Mutation)
		g.P("// ", verb, msg.Name, f.GoName, " applies an atomic mutation to the ", f.GoName, " field of ", msg.Name, ".")
		g.P("func (r *", lowerName, "Repository) ", verb, msg.Name, f.GoName, "(ctx context.Context, tr fdblayer.Transaction, dir directory.DirectorySubspace, ", fieldParamDecls(msg.PrimaryKeyFields), ", val ", FieldGoType(f), ") error {")
		g.P("	if err := ctx.Err(); err != nil {")
		g.P("		return err")
		g.P("	}")
		g.P(`	typeID, err := r.store.GetTypeID("`, msg.Name, `")`)
		g.P("	if err != nil {")
		g.P("		return err")
		g.P("	}")
		g.P("	key := dir.Pack(tuple.Tuple{typeID, fdblayer.FieldNamespace, ", pkArgsStr, ", ", f.Number, "})")
		g.P()
		g.P("	buf := make([]byte, 8)")
		g.P("	binary.LittleEndian.PutUint64(buf, ", encodeAtomicUint64Expr("val", f), ")")
		g.P()
		g.P("	tr.", verb, "(key, buf)")
		g.P("	return nil")
		g.P("}")
		g.P()

		g.P("// Set", msg.Name, f.GoName, " explicitly sets or resets the atomic ", f.GoName, " field of ", msg.Name, " in FieldNamespace.")
		g.P("func (r *", lowerName, "Repository) Set", msg.Name, f.GoName, "(ctx context.Context, tr fdblayer.Transaction, dir directory.DirectorySubspace, ", fieldParamDecls(msg.PrimaryKeyFields), ", val ", FieldGoType(f), ") error {")
		g.P("	if err := ctx.Err(); err != nil {")
		g.P("		return err")
		g.P("	}")
		g.P(`	typeID, err := r.store.GetTypeID("`, msg.Name, `")`)
		g.P("	if err != nil {")
		g.P("		return err")
		g.P("	}")
		g.P("	key := dir.Pack(tuple.Tuple{typeID, fdblayer.FieldNamespace, ", pkArgsStr, ", ", f.Number, "})")
		if f.Mutation == ir.MutationMax && !f.IsUnsigned {
			g.P("	buf := make([]byte, 8)")
			g.P("	binary.LittleEndian.PutUint64(buf, ", encodeAtomicUint64Expr("val", f), ")")
			g.P("	tr.Set(key, buf)")
		} else {
			g.P("	if val == 0 {")
			g.P("		tr.Clear(key)")
			g.P("	} else {")
			g.P("		buf := make([]byte, 8)")
			g.P("		binary.LittleEndian.PutUint64(buf, ", encodeAtomicUint64Expr("val", f), ")")
			g.P("		tr.Set(key, buf)")
			g.P("	}")
		}
		g.P("	return nil")
		g.P("}")
		g.P()
	}
}

func encodeAtomicUint64Expr(expr string, f ir.FieldSpec) string {
	if !f.IsUnsigned && (f.Mutation == ir.MutationMax || f.Mutation == ir.MutationMin) {
		if FieldGoType(f) == "int64" {
			return fmt.Sprintf("uint64(%s)^(1<<63)", expr)
		}
		return fmt.Sprintf("uint64(int64(%s))^(1<<63)", expr)
	}
	return fmt.Sprintf("uint64(%s)", expr)
}

func decodeAtomicGoExpr(sliceExpr string, f ir.FieldSpec) string {
	if !f.IsUnsigned && (f.Mutation == ir.MutationMax || f.Mutation == ir.MutationMin) {
		if FieldGoType(f) == "int64" {
			return fmt.Sprintf("int64(binary.LittleEndian.Uint64(%s) ^ (1 << 63))", sliceExpr)
		}
		return fmt.Sprintf("%s(int64(binary.LittleEndian.Uint64(%s) ^ (1 << 63)))", FieldGoType(f), sliceExpr)
	}
	return fmt.Sprintf("%s(binary.LittleEndian.Uint64(%s))", FieldGoType(f), sliceExpr)
}

func generateMarshalWithZeroedAtomics(g Printer, msg ir.MessageSpec) {
	hasMut := ir.HasMutationFields(msg)
	hasVS := ir.MsgHasVersionstampPK(msg)
	if hasMut || hasVS {
		var nonZeroChecks []string
		for _, f := range msg.Fields {
			if f.Mutation != ir.MutationNone {
				nonZeroChecks = append(nonZeroChecks, fmt.Sprintf("entity.%s != 0", f.GoName))
			} else if f.IsVersionstamp {
				nonZeroChecks = append(nonZeroChecks, fmt.Sprintf("len(entity.%s) > 0", f.GoName))
			}
		}
		g.P("	// Marshal without mutating the caller's struct in-place.")
		g.P("	marshalTarget := entity")
		g.P("	if ", strings.Join(nonZeroChecks, " || "), " {")
		g.P("		marshalTarget = &", msg.Name, "{")
		for _, f := range msg.Fields {
			if f.Mutation == ir.MutationNone && !f.IsVersionstamp {
				g.P("			", f.GoName, ": entity.", f.GoName, ",")
			}
		}
		g.P("		}")
		g.P("	}")
		g.P("	value, err := proto.Marshal(marshalTarget)")
	} else {
		g.P("	value, err := proto.Marshal(entity)")
	}
	g.P("	if err != nil {")
	g.P("		return err")
	g.P("	}")
	g.P()
}

func generateUnmarshalAtomicFields(g Printer, msg ir.MessageSpec, sliceExpr string, indent string) {
	for _, f := range msg.Fields {
		if f.Mutation != ir.MutationNone {
			g.P(indent, "entity.", f.GoName, " = 0")
		}
	}
	g.P(indent, "for _, fkv := range ", sliceExpr, " {")
	g.P(indent, "	if len(fkv.Value) < 8 {")
	g.P(indent, "		continue")
	g.P(indent, "	}")
	g.P(indent, "	ftpl, err := dir.Unpack(fkv.Key)")
	g.P(indent, "	if err != nil || len(ftpl) == 0 {")
	g.P(indent, "		continue")
	g.P(indent, "	}")
	g.P(indent, "	fieldNum, ok := ftpl[len(ftpl)-1].(int64)")
	g.P(indent, "	if !ok {")
	g.P(indent, "		continue")
	g.P(indent, "	}")
	g.P(indent, "	switch fieldNum {")
	for _, f := range msg.Fields {
		if f.Mutation != ir.MutationNone {
			g.P(indent, "	case ", f.Number, ":")
			g.P(indent, "		entity.", f.GoName, " = ", decodeAtomicGoExpr("fkv.Value", f))
		}
	}
	g.P(indent, "	}")
	g.P(indent, "}")
}

// FieldGoType returns the Go type string for an ir.FieldSpec.
func FieldGoType(f ir.FieldSpec) string {
	if f.Kind == ir.KindEnum && f.EnumGoName != "" {
		return f.EnumGoName
	}
	if f.Kind == ir.KindMessage && f.MessageGoName != "" {
		return "*" + f.MessageGoName
	}
	return GoType(f.Kind)
}

// GoType maps an ir.FieldKind to its scalar Go type string.
func GoType(kind ir.FieldKind) string {
	switch kind {
	case ir.KindInt32, ir.KindSint32, ir.KindSfixed32:
		return "int32"
	case ir.KindUint32, ir.KindFixed32:
		return "uint32"
	case ir.KindInt64, ir.KindSint64, ir.KindSfixed64:
		return "int64"
	case ir.KindUint64, ir.KindFixed64:
		return "uint64"
	case ir.KindFloat:
		return "float32"
	case ir.KindDouble:
		return "float64"
	case ir.KindString:
		return "string"
	case ir.KindBool:
		return "bool"
	case ir.KindBytes:
		return "[]byte"
	default:
		return "interface{}"
	}
}

// JoinFieldNames joins field GoNames with "And".
func JoinFieldNames(fields []ir.FieldSpec) string {
	names := make([]string, 0, len(fields))
	for _, f := range fields {
		names = append(names, f.GoName)
	}
	return strings.Join(names, "And")
}

// HasBinaryImports returns true if the message requires "encoding/binary".
func HasBinaryImports(msg ir.MessageSpec) bool {
	return ir.HasMutationFields(msg)
}

// HasBytesImports returns true if the message requires "bytes" for index comparisons.
func HasBytesImports(msg ir.MessageSpec) bool {
	for _, idx := range msg.SecondaryIndexes {
		for _, f := range idx.Fields {
			if f.Kind == ir.KindBytes && !f.IsRepeated {
				return true
			}
		}
	}
	return false
}

// PackField normalizes a Go expression for FDB tuple packing.
func PackField(name string, f ir.FieldSpec) string {
	if f.IsVersionstamp {
		return "fdblayer.BytesToVersionstamp(" + name + ")"
	}
	goType := FieldGoType(f)
	if f.IsUnsigned || goType == "uint32" || goType == "uint64" {
		return "uint64(" + name + ")"
	}
	if f.IsEnum || goType == "int32" || goType == "int64" {
		return "int64(" + name + ")"
	}
	return name
}

// FieldNotEqual returns a Go inequality expression for a field.
func FieldNotEqual(lhs, rhs string, f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return fmt.Sprintf("!bytes.Equal(%s, %s)", lhs, rhs)
	}
	return fmt.Sprintf("%s != %s", lhs, rhs)
}

// FieldEqual returns a Go equality expression for a field.
func FieldEqual(lhs, rhs string, f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return fmt.Sprintf("bytes.Equal(%s, %s)", lhs, rhs)
	}
	return fmt.Sprintf("%s == %s", lhs, rhs)
}

// HasNonRepeatedFields returns true if any field in fields is non-repeated.
func HasNonRepeatedFields(fields []ir.FieldSpec) bool {
	for _, f := range fields {
		if !f.IsRepeated {
			return true
		}
	}
	return false
}

// NonRepeatedFieldsEqual returns a Go conjunction comparing all non-repeated fields between old and entity.
func NonRepeatedFieldsEqual(fields []ir.FieldSpec) string {
	var parts []string
	for _, f := range fields {
		if !f.IsRepeated {
			parts = append(parts, FieldEqual("old."+f.GoName, "entity."+f.GoName, f))
		}
	}
	return strings.Join(parts, " && ")
}

// MapKeyType returns a comparable Go map key type for fan-out index diffing.
func MapKeyType(f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return "string"
	}
	return FieldGoType(f)
}

// MapKeyExpr converts an expression into a comparable Go map key.
func MapKeyExpr(expr string, f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return "string(" + expr + ")"
	}
	return expr
}

// MutationVerb returns the Go method prefix ("Add", "Max", "Min") for an atomic mutation.
func MutationVerb(m ir.MutationType) string {
	switch m {
	case ir.MutationAdd:
		return "Add"
	case ir.MutationMax:
		return "Max"
	case ir.MutationMin:
		return "Min"
	default:
		return "Set"
	}
}

func pkTypeExpr(msg ir.MessageSpec) string {
	if len(msg.PrimaryKeyFields) == 1 {
		return FieldGoType(msg.PrimaryKeyFields[0])
	}
	if len(msg.PrimaryKeyFields) > 1 {
		return msg.Name + "PrimaryKey"
	}
	return "struct{}"
}

func pkTupleArgsFromEntity(msg ir.MessageSpec, varName string) string {
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		parts = append(parts, PackField(fmt.Sprintf("%s.%s", varName, f.GoName), f))
	}
	return strings.Join(parts, ", ")
}

func pkTupleArgsFromParam(msg ir.MessageSpec) string {
	if len(msg.PrimaryKeyFields) == 1 {
		return PackField("pk", msg.PrimaryKeyFields[0])
	}
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		parts = append(parts, PackField("pk."+f.GoName, f))
	}
	return strings.Join(parts, ", ")
}

func versionstampedPKTupleArgsWithVar(msg ir.MessageSpec, userVersionExpr string) string {
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		if f.IsVersionstamp {
			parts = append(parts, "tuple.IncompleteVersionstamp("+userVersionExpr+")")
		} else {
			parts = append(parts, PackField("entity."+f.GoName, f))
		}
	}
	return strings.Join(parts, ", ")
}

func indexFieldTupleArgs(fields []ir.FieldSpec, varName string) string {
	parts := make([]string, 0, len(fields))
	for _, f := range fields {
		parts = append(parts, PackField(fmt.Sprintf("%s.%s", varName, f.GoName), f))
	}
	return strings.Join(parts, ", ")
}

func fieldParamDecls(fields []ir.FieldSpec) string {
	parts := make([]string, 0, len(fields))
	for _, f := range fields {
		parts = append(parts, f.GoName+" "+FieldGoType(f))
	}
	return strings.Join(parts, ", ")
}

func emitFanOutIndexWrite(g Printer, msg ir.MessageSpec, idx ir.SecondaryIndexSpec, repeatedIdx int, varName string, isSet bool, indent string) {
	op := "Clear"
	if isSet {
		op = "Set"
	}
	g.P(indent, "tr.", op, "(dir.Pack(tuple.Tuple{typeID, fdblayer.IndexNamespace, ", idx.IndexID, ",")
	for j, sf := range idx.Fields {
		if j == repeatedIdx {
			g.P(indent, "\t", PackField("item", sf), ",")
		} else {
			g.P(indent, "\t", PackField(varName+"."+sf.GoName, sf), ",")
		}
	}
	for _, pkf := range msg.PrimaryKeyFields {
		g.P(indent, "\t", PackField(varName+"."+pkf.GoName, pkf), ",")
	}
	if isSet {
		g.P(indent, "}), []byte{})")
	} else {
		g.P(indent, "}))")
	}
}

func emitVersionstampedFanOutIndexWrite(g Printer, msg ir.MessageSpec, idx ir.SecondaryIndexSpec, repeatedIdx int, varName string, userVersionVar string, indent string) {
	g.P(indent, "idxKey, err := dir.PackWithVersionstamp(tuple.Tuple{typeID, fdblayer.IndexNamespace, ", idx.IndexID, ",")
	for j, sf := range idx.Fields {
		if j == repeatedIdx {
			g.P(indent, "\t", PackField("item", sf), ",")
		} else {
			g.P(indent, "\t", PackField(varName+"."+sf.GoName, sf), ",")
		}
	}
	for _, pkf := range msg.PrimaryKeyFields {
		if pkf.IsVersionstamp {
			g.P(indent, "\t", "tuple.IncompleteVersionstamp(", userVersionVar, "),")
		} else {
			g.P(indent, "\t", PackField(varName+"."+pkf.GoName, pkf), ",")
		}
	}
	g.P(indent, "})")
	g.P(indent, "if err != nil {")
	g.P(indent, "	return err")
	g.P(indent, "}")
	g.P(indent, "tr.SetVersionstampedKey(idxKey, []byte{})")
}

