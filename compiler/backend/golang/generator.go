// Printer abstracts protogen.GeneratedFile.P so Go repository generation can be unit-tested without protogen.
type Printer = backend.Printer

// Backend implements backend.Generator for Go repository code generation.
type Backend struct{}

// NewBackend returns a new Go code generator backend.
func NewBackend() *Backend {
	return &Backend{}
}

// Language returns the canonical language identifier ("go").
func (b *Backend) Language() string {
	return "go"
}

// GenerateFile transforms a language-neutral ir.FileSpec into one .fdb.go file per annotated message.
func (b *Backend) GenerateFile(file *ir.FileSpec, opts backend.Options) ([]backend.GeneratedFile, error) {
	if file == nil {
		return nil, nil
	}
	annotated := file.AnnotatedMessages()
	if len(annotated) == 0 {
		return nil, nil
	}
	outputs := make([]backend.GeneratedFile, 0, len(annotated))
	for _, msg := range annotated {
		if msg.GoPackagePath == "" {
			msg.GoPackagePath = file.GoImportPath
		}
		if msg.GoPackageName == "" {
			msg.GoPackageName = file.GoPackageName
		}
		if msg.FilePrefix == "" {
			msg.FilePrefix = file.GeneratedFilenamePrefix
		}
		var buf backend.BufferPrinter
		GenerateMessage(&buf, msg)
		fileName := msg.FilePrefix + "_" + strings.ToLower(msg.Name) + ".fdb.go"
		outputs = append(outputs, backend.GeneratedFile{
			Filename:     fileName,
			GoImportPath: msg.GoPackagePath,
			Content:      buf.Bytes(),
		})
	}
	return outputs, nil
}

// GenerateMessage emits the complete Go repository code for a single Protobuf message.
func GenerateMessage(g Printer, msg ir.MessageSpec) {
	if msg.IsQueue {
		msg.PrimaryKeyFields = ir.ReorderQueuePrimaryKeyFields(msg.PrimaryKeyFields)
	}
	generateHeader(g, msg)
	if msg.IsQueue {
		generateQueueRepository(g, msg)
	} else {
		generateEntityRepository(g, msg)
	}
}

func generateHeader(g Printer, msg ir.MessageSpec) {
	g.P("// Code generated by protoc-gen-fdb-go. DO NOT EDIT.")
	g.P("// Source: ", msg.GoPackagePath)
	g.P()
	g.P("package ", msg.GoPackageName)
	g.P()
	g.P("import (")
	if !msg.IsQueue && HasBytesImports(msg) {
		g.P(`	"bytes"`)
	}
	g.P(`	"context"`)
	g.P(`	"fmt"`)
	g.P()
	g.P(`	"github.com/apple/foundationdb/bindings/go/src/fdb"`)
	g.P(`	"github.com/apple/foundationdb/bindings/go/src/fdb/directory"`)
	g.P(`	"github.com/apple/foundationdb/bindings/go/src/fdb/tuple"`)
	g.P(`	fdblayer "github.com/romannikov/fdb-layer/runtimes/go"`)
	g.P(`	"google.golang.org/protobuf/proto"`)
	g.P(")")
	g.P()
}

func versionstampFieldName(msg ir.MessageSpec) string {
	for _, f := range msg.PrimaryKeyFields {
		if f.IsVersionstamp {
			return f.GoName
		}
	}
	return ""
}

func typeIDConstName(msg ir.MessageSpec) string {
	return msg.Name + "TypeID"
}

func effectiveTypeID(msg ir.MessageSpec) int64 {
	return msg.TypeID
}

// IndexConstName returns the generated fdblayer.IndexID constant name for a secondary index.
func IndexConstName(msg ir.MessageSpec, idx ir.SecondaryIndexSpec) string {
	var b strings.Builder
	b.WriteString(msg.Name)
	b.WriteString("By")
	for _, f := range idx.Fields {
		b.WriteString(f.GoName)
	}
	return b.String()
}

func generateQueueRepository(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	typeIDConst := typeIDConstName(msg)

	g.P("// ", typeIDConst, " is the compile-time type prefix for ", msg.Name, " records in FoundationDB.")
	g.P("const ", typeIDConst, " int64 = ", effectiveTypeID(msg))
	g.P()
	g.P("// ", msg.Name, "Repository defines the repository interface for the ", msg.Name, " queue.")
	g.P("type ", msg.Name, "Repository interface {")
	g.P("	fdblayer.QueueRepository[*", msg.Name, "]")
	g.P("}")
	g.P()
	g.P("type ", lowerName, "Repository struct {")
	g.P("	dir directory.DirectorySubspace")
	g.P("}")
	g.P()
	g.P("// New", msg.Name, "Repository creates a new ", msg.Name, "Repository instance.")
	g.P("func New", msg.Name, "Repository(dir directory.DirectorySubspace) ", msg.Name, "Repository {")
	g.P("	return &", lowerName, "Repository{dir: dir}")
	g.P("}")
	g.P()

	generateEnqueue(g, msg)
	generateDequeue(g, msg)
	generateDequeueBatch(g, msg)
}

func generateEnqueue(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	hasVS := ir.MsgHasVersionstampPK(msg)
	typeIDConst := typeIDConstName(msg)

	g.P("// Enqueue adds a ", msg.Name, " to the queue.")
	g.P("func (r *", lowerName, "Repository) Enqueue(ctx context.Context, tr fdblayer.Transaction, entity *", msg.Name, ", opts ...fdblayer.WriteOption) error {")
	g.P("	if err := ctx.Err(); err != nil {")
	g.P("		return err")
	g.P("	}")
	g.P("	if entity == nil {")
	g.P(`		return fmt.Errorf("`, lowerName, ` entity cannot be nil")`)
	g.P("	}")
	g.P("	dir := r.dir")
	g.P()
	if hasVS {
		g.P("	writeCfg := fdblayer.ApplyWriteOptions(opts)")
		g.P("	key, err := dir.PackWithVersionstamp(tuple.Tuple{", typeIDConst, ", fdblayer.DataNamespace, ", versionstampedPKTupleArgsWithVar(msg, "writeCfg.UserVersion"), "})")
		g.P("	if err != nil {")
		g.P("		return err")
		g.P("	}")
	} else {
		g.P("	key := dir.Pack(tuple.Tuple{", typeIDConst, ", fdblayer.DataNamespace, ", pkTupleArgsFromEntity(msg, "entity"), "})")
	}
	g.P()
	generateMarshalRecord(g, msg)
	if hasVS {
		g.P("	tr.SetVersionstampedKey(key, value)")
	} else {
		g.P("	tr.Set(key, value)")
	}
	g.P()
	g.P("	return nil")
	g.P("}")
	g.P()
}

func generateDequeue(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	typeIDConst := typeIDConstName(msg)
	partitionSchema := schemaSliceExpr(msg.PrimaryKeyFields[:1])

	g.P("// Dequeue reads and removes the single oldest message from the queue.")
	g.P("func (r *", lowerName, "Repository) Dequeue(ctx context.Context, tr fdblayer.Transaction, partitionKey fdblayer.Key) (*", msg.Name, ", error) {")
	g.P("	if err := ctx.Err(); err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	if len(partitionKey) != 1 {")
	g.P(`		return nil, fmt.Errorf("%w: expected 1 partition key element for `, lowerName, `, got %d", fdblayer.ErrInvalidKey, len(partitionKey))`)
	g.P("	}")
	g.P("	dir := r.dir")
	g.P()
	g.P("	prefixKey, err := fdblayer.PackSubspaceTuple(dir, tuple.Tuple{", typeIDConst, ", fdblayer.DataNamespace}, partitionKey, ", partitionSchema, ")")
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	prefixRange := fdb.KeyRange{")
	g.P("		Begin: fdb.Key(append(append([]byte(nil), prefixKey...), 0x00)),")
	g.P("		End:   fdb.Key(append(append([]byte(nil), prefixKey...), 0xFF)),")
	g.P("	}")
	g.P()
	g.P("	rows := fdblayer.GetRange(tr, prefixRange, fdb.RangeOptions{Limit: 1}).GetSliceOrPanic()")
	g.P("	if len(rows) == 0 {")
	g.P("		return nil, nil")
	g.P("	}")
	g.P()
	g.P("	firstItem := rows[0]")
	g.P("	keyToDelete := firstItem.Key")
	g.P("	payload := firstItem.Value")
	g.P()
	g.P("	entity := &", msg.Name, "{}")
	g.P("	if err := proto.Unmarshal(payload, entity); err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P()
	if ir.MsgHasVersionstampPK(msg) {
		g.P("	tpl, unpackErr := dir.Unpack(keyToDelete)")
		g.P("	if unpackErr != nil {")
		g.P("		return nil, unpackErr")
		g.P("	}")
		for i, f := range msg.PrimaryKeyFields {
			if f.IsVersionstamp {
				g.P("	if len(tpl) > ", i, "+2 {")
				g.P("		if vs, ok := tpl[", i, "+2].(tuple.Versionstamp); ok {")
				g.P("			entity.", f.GoName, " = vs.Bytes()")
				g.P("		}")
				g.P("	}")
			}
		}
		g.P()
	}
	g.P("	tr.Clear(keyToDelete)")
	g.P("	return entity, nil")
	g.P("}")
	g.P()
}

func generateDequeueBatch(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	typeIDConst := typeIDConstName(msg)
	partitionSchema := schemaSliceExpr(msg.PrimaryKeyFields[:1])

	g.P("// DequeueBatch reads and removes up to limit oldest messages from the queue in a single range scan.")
	g.P("func (r *", lowerName, "Repository) DequeueBatch(ctx context.Context, tr fdblayer.Transaction, partitionKey fdblayer.Key, limit int) ([]*", msg.Name, ", error) {")
	g.P("	if err := ctx.Err(); err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	if len(partitionKey) != 1 {")
	g.P(`		return nil, fmt.Errorf("%w: expected 1 partition key element for `, lowerName, `, got %d", fdblayer.ErrInvalidKey, len(partitionKey))`)
	g.P("	}")
	g.P("	dir := r.dir")
	g.P()
	g.P("	prefixKey, err := fdblayer.PackSubspaceTuple(dir, tuple.Tuple{", typeIDConst, ", fdblayer.DataNamespace}, partitionKey, ", partitionSchema, ")")
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	if limit <= 0 {")
	g.P("		return nil, nil")
	g.P("	}")
	g.P("	prefixRange := fdb.KeyRange{")
	g.P("		Begin: fdb.Key(append(append([]byte(nil), prefixKey...), 0x00)),")
	g.P("		End:   fdb.Key(append(append([]byte(nil), prefixKey...), 0xFF)),")
	g.P("	}")
	g.P()
	g.P("	rows := fdblayer.GetRange(tr, prefixRange, fdb.RangeOptions{Limit: limit}).GetSliceOrPanic()")
	g.P("	if len(rows) == 0 {")
	g.P("		return nil, nil")
	g.P("	}")
	g.P()
	g.P("	items := make([]*", msg.Name, ", 0, len(rows))")
	g.P("	for _, row := range rows {")
	g.P("		if err := ctx.Err(); err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	g.P("		entity := &", msg.Name, "{}")
	g.P("		if err := proto.Unmarshal(row.Value, entity); err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	if ir.MsgHasVersionstampPK(msg) {
		g.P("		tpl, unpackErr := dir.Unpack(row.Key)")
		g.P("		if unpackErr != nil {")
		g.P("			return nil, unpackErr")
		g.P("		}")
		for i, f := range msg.PrimaryKeyFields {
			if f.IsVersionstamp {
				g.P("		if len(tpl) > ", i, "+2 {")
				g.P("			if vs, ok := tpl[", i, "+2].(tuple.Versionstamp); ok {")
				g.P("				entity.", f.GoName, " = vs.Bytes()")
				g.P("			}")
				g.P("		}")
			}
		}
	}
	g.P("		tr.Clear(row.Key)")
	g.P("		items = append(items, entity)")
	g.P("	}")
	g.P("	return items, nil")
	g.P("}")
}

func generateEntityRepository(g Printer, msg ir.MessageSpec) {
	generateTypesAndInterface(g, msg)
	generateInsert(g, msg)
	generateUpsert(g, msg)
	generateDelete(g, msg)
	generateReadRow(g, msg)
	generateReadRows(g, msg)
	generateScan(g, msg)
	generateScanIndex(g, msg)
}

