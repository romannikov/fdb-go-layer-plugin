// Printer abstracts protogen.GeneratedFile.P so Go repository generation can be unit-tested without protogen.
type Printer = backend.Printer

// Backend implements backend.Generator for Go repository code generation.
type Backend struct{}

// NewBackend returns a new Go code generator backend.
func NewBackend() *Backend {
	return &Backend{}
}

// Language returns the canonical language identifier ("go").
func (b *Backend) Language() string {
	return "go"
}

// GenerateFile transforms a language-neutral ir.FileSpec into one .fdb.go file per annotated message.
func (b *Backend) GenerateFile(file *ir.FileSpec, opts backend.Options) ([]backend.GeneratedFile, error) {
	if file == nil {
		return nil, nil
	}
	annotated := file.AnnotatedMessages()
	if len(annotated) == 0 {
		return nil, nil
	}
	outputs := make([]backend.GeneratedFile, 0, len(annotated))
	for _, msg := range annotated {
		if msg.GoPackagePath == "" {
			msg.GoPackagePath = file.GoImportPath
		}
		if msg.GoPackageName == "" {
			msg.GoPackageName = file.GoPackageName
		}
		if msg.FilePrefix == "" {
			msg.FilePrefix = file.GeneratedFilenamePrefix
		}
		var buf backend.BufferPrinter
		GenerateMessage(&buf, msg)
		fileName := msg.FilePrefix + "_" + strings.ToLower(msg.Name) + ".fdb.go"
		outputs = append(outputs, backend.GeneratedFile{
			Filename:     fileName,
			GoImportPath: msg.GoPackagePath,
			Content:      buf.Bytes(),
		})
	}
	return outputs, nil
}

// GenerateMessage emits the complete Go repository code for a single Protobuf message.
func GenerateMessage(g Printer, msg ir.MessageSpec) {
	if msg.IsQueue {
		msg.PrimaryKeyFields = ir.ReorderQueuePrimaryKeyFields(msg.PrimaryKeyFields)
	} else {
		hasVS := ir.MsgHasVersionstampPK(msg)
		if len(msg.PrimaryKeyPrefixes) == 0 && len(msg.PrimaryKeyRangeScans) == 0 {
			msg.PrimaryKeyPrefixes, msg.PrimaryKeyRangeScans = ir.PopulatePrimaryKeyScans(msg.PrimaryKeyFields, msg.IsQueue, hasVS)
		}
		msg.SecondaryIndexes = ir.PopulateIndexPrefixesWithPK(msg.SecondaryIndexes, msg.PrimaryKeyFields, msg.IsQueue, hasVS)
	}
	generateHeader(g, msg)
	if msg.IsQueue {
		generateQueueRepository(g, msg)
	} else {
		generateEntityRepository(g, msg)
	}
}

func generateHeader(g Printer, msg ir.MessageSpec) {
	g.P("// Code generated by protoc-gen-fdb-go. DO NOT EDIT.")
	g.P("// Source: ", msg.GoPackagePath)
	g.P()
	g.P("package ", msg.GoPackageName)
	g.P()
	g.P("import (")
	if !msg.IsQueue && HasBytesImports(msg) {
		g.P(`	"bytes"`)
	}
	g.P(`	"context"`)
	if !msg.IsQueue && HasBinaryImports(msg) {
		g.P(`	"encoding/binary"`)
	}
	if !msg.IsQueue {
		g.P(`	"fmt"`)
	}
	g.P()
	g.P(`	"github.com/apple/foundationdb/bindings/go/src/fdb"`)
	g.P(`	"github.com/apple/foundationdb/bindings/go/src/fdb/tuple"`)
	g.P(`	fdblayer "github.com/romannikov/fdb-layer/runtimes/go"`)
	g.P(`	"google.golang.org/protobuf/proto"`)
	g.P(")")
	g.P()
}

func typeIDConstName(msg ir.MessageSpec) string {
	return msg.Name + "TypeID"
}

func effectiveTypeID(msg ir.MessageSpec) int64 {
	if msg.TypeID != 0 {
		return msg.TypeID
	}
	return ir.ComputeTypeID(msg.Name)
}

func canEmitReplace(msg ir.MessageSpec) bool {
	return !msg.IsQueue && !ir.MsgHasVersionstampPK(msg) && len(msg.SecondaryIndexes) == 0 && len(msg.Children) == 0
}

func generateEntityRepository(g Printer, msg ir.MessageSpec) {
	generateTypesAndInterface(g, msg)
	generateCreate(g, msg)
	generateGet(g, msg)
	generateSet(g, msg)
	generateDelete(g, msg)
	generateBatchGet(g, msg)
	generateList(g, msg)
	for _, prefix := range msg.PrimaryKeyPrefixes {
		generateListByPKPrefix(g, msg, prefix.Fields)
	}
	for _, rs := range msg.PrimaryKeyRangeScans {
		generateScanByPKRange(g, msg, rs)
	}
	if len(msg.Children) > 0 {
		generateGetWithChildren(g, msg)
	}
	generateMutations(g, msg)
	for _, idx := range msg.SecondaryIndexes {
		if idx.Aggregate != ir.AggregateNone {
			generateAggregateGetter(g, msg, idx)
			continue
		}
		generateGetByIndex(g, msg, idx, idx.Fields)
		for _, prefix := range idx.Prefixes {
			generateGetByIndex(g, msg, idx, prefix.Fields)
		}
		if idx.IsUnique {
			generateGetUniqueByIndex(g, msg, idx)
		}
		for _, rs := range idx.RangeScans {
			generateScanByIndex(g, msg, idx, rs)
		}
		if idx.IsCovering() {
			generateGetCoveredByIndex(g, msg, idx, idx.Fields)
			for _, cp := range idx.CoveredPrefixes {
				generateGetCoveredByIndex(g, msg, idx, cp.Fields)
			}
			for _, crs := range idx.CoveredRangeScans {
				generateScanCoveredByIndex(g, msg, idx, crs)
			}
		}
	}
	generateAtomicMutators(g, msg)
}

func generateTypesAndInterface(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	pkType := pkTypeExpr(msg)
	typeIDConst := typeIDConstName(msg)

	g.P("// ", typeIDConst, " is the compile-time type prefix for ", msg.Name, " records in FoundationDB.")
	g.P("const ", typeIDConst, " int64 = ", effectiveTypeID(msg))
	g.P()

	if len(msg.PrimaryKeyFields) > 1 {
		g.P("// ", msg.Name, "PrimaryKey represents the compound primary key for ", msg.Name, ".")
		g.P("type ", msg.Name, "PrimaryKey struct {")
		for _, f := range msg.PrimaryKeyFields {
			g.P("	", f.GoName, " ", FieldGoType(f))
		}
		g.P("}")
		g.P()
	}

	if len(msg.Children) > 0 {
		g.P("// ", msg.Name, "WithChildren holds a parent ", msg.Name, " entity and all interleaved child records.")
		g.P("type ", msg.Name, "WithChildren struct {")
		g.P("	", msg.Name, " *", msg.Name)
		for _, child := range msg.Children {
			g.P("	", child.Name, "s []*", child.Name)
		}
		g.P("}")
		g.P()
	}

	g.P("// ", msg.Name, "Repository defines the repository interface for ", msg.Name, ".")
	g.P("type ", msg.Name, "Repository interface {")
	g.P("	fdblayer.GenericRepository[*", msg.Name, ", ", pkType, "]")
	if canEmitReplace(msg) {
		g.P("	Replace(entity *", msg.Name, ") fdblayer.Mutation")
	}
	if len(msg.Children) > 0 {
		g.P("	GetWithChildren(ctx context.Context, tx fdblayer.ReadTx, pk ", pkType, ") (*", msg.Name, "WithChildren, error)")
	}
	for _, prefix := range msg.PrimaryKeyPrefixes {
		joined := JoinFieldNames(prefix.Fields)
		g.P("	ListBy", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(prefix.Fields), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
	}
	for _, rs := range msg.PrimaryKeyRangeScans {
		joined := JoinFieldNames(rs.AllFields())
		g.P("	ScanBy", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", rangeScanParamDecls(rs), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
	}
	if len(msg.SecondaryIndexes) > 0 || ir.HasMutationFields(msg) {
		g.P()
	}
	for _, idx := range msg.SecondaryIndexes {
		joined := JoinFieldNames(idx.Fields)
		if idx.Aggregate != ir.AggregateNone {
			switch idx.Aggregate {
			case ir.AggregateCount:
				g.P("	GetCountBy", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(idx.Fields), ") (int64, error)")
			case ir.AggregateSum:
				g.P("	GetSum", idx.AggregateField.GoName, "By", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(idx.Fields), ") (int64, error)")
			case ir.AggregateMin:
				g.P("	GetMin", idx.AggregateField.GoName, "By", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(idx.Fields), ") (", FieldGoType(*idx.AggregateField), ", bool, error)")
			case ir.AggregateMax:
				g.P("	GetMax", idx.AggregateField.GoName, "By", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(idx.Fields), ") (", FieldGoType(*idx.AggregateField), ", bool, error)")
			}
			continue
		}
		g.P("	GetBy", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(idx.Fields), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
		for _, prefix := range idx.Prefixes {
			prefixJoined := JoinFieldNames(prefix.Fields)
			g.P("	GetBy", prefixJoined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(prefix.Fields), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
		}
		if idx.IsUnique {
			g.P("	GetUniqueBy", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(idx.Fields), ") (*", msg.Name, ", error)")
		}
		for _, rs := range idx.RangeScans {
			rsJoined := JoinFieldNames(rs.AllFields())
			g.P("	ScanBy", rsJoined, "(ctx context.Context, tx fdblayer.ReadTx, ", rangeScanParamDecls(rs), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
		}
		if idx.IsCovering() {
			g.P("	GetCoveredBy", joined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(idx.Fields), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
			for _, cp := range idx.CoveredPrefixes {
				cpJoined := JoinFieldNames(cp.Fields)
				g.P("	GetCoveredBy", cpJoined, "(ctx context.Context, tx fdblayer.ReadTx, ", fieldParamDecls(cp.Fields), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
			}
			for _, crs := range idx.CoveredRangeScans {
				crsJoined := JoinFieldNames(crs.AllFields())
				g.P("	ScanCoveredBy", crsJoined, "(ctx context.Context, tx fdblayer.ReadTx, ", rangeScanParamDecls(crs), ", opts fdblayer.PaginationOptions) (*fdblayer.PaginatedResult[*", msg.Name, "], error)")
			}
		}
	}
	for _, f := range msg.Fields {
		if f.Mutation != ir.MutationNone {
			verb := MutationVerb(f.Mutation)
			g.P("	", verb, f.GoName, "(ctx context.Context, tx *fdblayer.Tx, pk ", pkType, ", val ", FieldGoType(f), ") error")
			g.P("	Set", f.GoName, "(ctx context.Context, tx *fdblayer.Tx, pk ", pkType, ", val ", FieldGoType(f), ") error")
			g.P("	", verb, f.GoName, "Mutation(pk ", pkType, ", val ", FieldGoType(f), ") fdblayer.Mutation")
			g.P("	Set", f.GoName, "Mutation(pk ", pkType, ", val ", FieldGoType(f), ") fdblayer.Mutation")
		}
	}
	g.P("}")
	g.P()
	g.P("type ", lowerName, "Repository struct{}")
	g.P()
	g.P("// New", msg.Name, "Repository creates a new ", msg.Name, "Repository instance.")
	g.P("func New", msg.Name, "Repository() ", msg.Name, "Repository {")
	g.P("	return &", lowerName, "Repository{}")
	g.P("}")
	g.P()
}

// FieldGoType returns the Go type string for an ir.FieldSpec.
func FieldGoType(f ir.FieldSpec) string {
	if f.Kind == ir.KindEnum && f.EnumGoName != "" {
		return f.EnumGoName
	}
	if f.Kind == ir.KindMessage && f.MessageGoName != "" {
		return "*" + f.MessageGoName
	}
	return GoType(f.Kind)
}

// GoType maps an ir.FieldKind to its scalar Go type string.
func GoType(kind ir.FieldKind) string {
	switch kind {
	case ir.KindInt32, ir.KindSint32, ir.KindSfixed32:
		return "int32"
	case ir.KindUint32, ir.KindFixed32:
		return "uint32"
	case ir.KindInt64, ir.KindSint64, ir.KindSfixed64:
		return "int64"
	case ir.KindUint64, ir.KindFixed64:
		return "uint64"
	case ir.KindFloat:
		return "float32"
	case ir.KindDouble:
		return "float64"
	case ir.KindString:
		return "string"
	case ir.KindBool:
		return "bool"
	case ir.KindBytes:
		return "[]byte"
	default:
		return "interface{}"
	}
}

// JoinFieldNames joins field GoNames with "And".
func JoinFieldNames(fields []ir.FieldSpec) string {
	names := make([]string, 0, len(fields))
	for _, f := range fields {
		names = append(names, f.GoName)
	}
	return strings.Join(names, "And")
}

// HasBinaryImports returns true if the message requires "encoding/binary".
func HasBinaryImports(msg ir.MessageSpec) bool {
	return ir.HasMutationFields(msg) || ir.HasAggregateIndexes(msg)
}

// HasBytesImports returns true if the message requires "bytes" for index comparisons or hierarchy reads.
func HasBytesImports(msg ir.MessageSpec) bool {
	if len(msg.Children) > 0 {
		return true
	}
	for _, idx := range msg.SecondaryIndexes {
		for _, f := range idx.Fields {
			if f.Kind == ir.KindBytes && !f.IsRepeated {
				return true
			}
		}
		for _, sf := range idx.StoringFields {
			if sf.Kind == ir.KindBytes && !sf.IsRepeated {
				return true
			}
		}
	}
	return false
}

// PackField normalizes a Go expression for FDB tuple packing.
func PackField(name string, f ir.FieldSpec) string {
	if f.IsVersionstamp {
		return "fdblayer.BytesToVersionstamp(" + name + ")"
	}
	goType := FieldGoType(f)
	if f.IsUnsigned || goType == "uint32" || goType == "uint64" {
		return "uint64(" + name + ")"
	}
	if f.IsEnum || goType == "int32" || goType == "int64" {
		return "int64(" + name + ")"
	}
	return name
}

// FieldNotEqual returns a Go inequality expression for a field.
func FieldNotEqual(lhs, rhs string, f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return fmt.Sprintf("!bytes.Equal(%s, %s)", lhs, rhs)
	}
	return fmt.Sprintf("%s != %s", lhs, rhs)
}

// FieldEqual returns a Go equality expression for a field.
func FieldEqual(lhs, rhs string, f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return fmt.Sprintf("bytes.Equal(%s, %s)", lhs, rhs)
	}
	return fmt.Sprintf("%s == %s", lhs, rhs)
}

// FieldNonZeroExpr returns a Go boolean expression checking that a scalar field is non-zero (for sparse indexes).
func FieldNonZeroExpr(varName string, f ir.FieldSpec) string {
	expr := varName + "." + f.GoName
	switch f.Kind {
	case ir.KindString, ir.KindBytes:
		return fmt.Sprintf("len(%s) > 0", expr)
	case ir.KindBool:
		return expr
	default:
		return fmt.Sprintf("%s != 0", expr)
	}
}

// SparseIndexPresentExpr returns a Go conjunction checking that all scalar fields in fields are non-zero.
func SparseIndexPresentExpr(fields []ir.FieldSpec, varName string) string {
	var parts []string
	for _, f := range fields {
		if f.IsRepeated {
			parts = append(parts, fmt.Sprintf("len(%s.%s) > 0", varName, f.GoName))
		} else {
			parts = append(parts, FieldNonZeroExpr(varName, f))
		}
	}
	if len(parts) == 0 {
		return "true"
	}
	return strings.Join(parts, " && ")
}

// HasNonRepeatedFields returns true if any field in fields is non-repeated.
func HasNonRepeatedFields(fields []ir.FieldSpec) bool {
	for _, f := range fields {
		if !f.IsRepeated {
			return true
		}
	}
	return false
}

// NonRepeatedFieldsEqual returns a Go conjunction comparing all non-repeated fields between old and entity.
func NonRepeatedFieldsEqual(fields []ir.FieldSpec) string {
	var parts []string
	for _, f := range fields {
		if !f.IsRepeated {
			parts = append(parts, FieldEqual("old."+f.GoName, "entity."+f.GoName, f))
		}
	}
	return strings.Join(parts, " && ")
}

// MapKeyType returns a comparable Go map key type for fan-out index diffing.
func MapKeyType(f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return "string"
	}
	return FieldGoType(f)
}

// MapKeyExpr converts an expression into a comparable Go map key.
func MapKeyExpr(expr string, f ir.FieldSpec) string {
	if f.Kind == ir.KindBytes {
		return "string(" + expr + ")"
	}
	return expr
}

// MutationVerb returns the Go method prefix ("Add", "Max", "Min") for an atomic mutation.
func MutationVerb(m ir.MutationType) string {
	switch m {
	case ir.MutationAdd:
		return "Add"
	case ir.MutationMax:
		return "Max"
	case ir.MutationMin:
		return "Min"
	default:
		return "Set"
	}
}

func pkTypeExpr(msg ir.MessageSpec) string {
	if len(msg.PrimaryKeyFields) == 1 {
		return FieldGoType(msg.PrimaryKeyFields[0])
	}
	if len(msg.PrimaryKeyFields) > 1 {
		return msg.Name + "PrimaryKey"
	}
	return "struct{}"
}

func pkTupleArgsFromEntity(msg ir.MessageSpec, varName string) string {
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		parts = append(parts, PackField(fmt.Sprintf("%s.%s", varName, f.GoName), f))
	}
	return strings.Join(parts, ", ")
}

func pkTupleArgsFromParam(msg ir.MessageSpec) string {
	return pkTupleArgsFromParamVar(msg, "pk")
}

func pkTupleArgsFromParamVar(msg ir.MessageSpec, paramVar string) string {
	if len(msg.PrimaryKeyFields) == 1 {
		return PackField(paramVar, msg.PrimaryKeyFields[0])
	}
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		parts = append(parts, PackField(paramVar+"."+f.GoName, f))
	}
	return strings.Join(parts, ", ")
}

func dataKeyTupleExprFromEntity(msg ir.MessageSpec, varName string) string {
	if msg.Interleave != nil {
		parentLen := len(msg.Interleave.ParentPKFields)
		var parentParts, childParts []string
		for _, f := range msg.PrimaryKeyFields[:parentLen] {
			parentParts = append(parentParts, PackField(fmt.Sprintf("%s.%s", varName, f.GoName), f))
		}
		for _, f := range msg.PrimaryKeyFields[parentLen:] {
			childParts = append(childParts, PackField(fmt.Sprintf("%s.%s", varName, f.GoName), f))
		}
		return fmt.Sprintf("tuple.Tuple{int64(%d), fdblayer.DataNamespace, %s, %s, %s}",
			msg.Interleave.ParentTypeID,
			strings.Join(parentParts, ", "),
			typeIDConstName(msg),
			strings.Join(childParts, ", "),
		)
	}
	return fmt.Sprintf("tuple.Tuple{%s, fdblayer.DataNamespace, %s}", typeIDConstName(msg), pkTupleArgsFromEntity(msg, varName))
}

func dataKeyTupleExprFromParam(msg ir.MessageSpec, paramVar string) string {
	if msg.Interleave != nil {
		parentLen := len(msg.Interleave.ParentPKFields)
		var parentParts, childParts []string
		for _, f := range msg.PrimaryKeyFields[:parentLen] {
			parentParts = append(parentParts, PackField(paramVar+"."+f.GoName, f))
		}
		for _, f := range msg.PrimaryKeyFields[parentLen:] {
			childParts = append(childParts, PackField(paramVar+"."+f.GoName, f))
		}
		return fmt.Sprintf("tuple.Tuple{int64(%d), fdblayer.DataNamespace, %s, %s, %s}",
			msg.Interleave.ParentTypeID,
			strings.Join(parentParts, ", "),
			typeIDConstName(msg),
			strings.Join(childParts, ", "),
		)
	}
	return fmt.Sprintf("tuple.Tuple{%s, fdblayer.DataNamespace, %s}", typeIDConstName(msg), pkTupleArgsFromParamVar(msg, paramVar))
}

func emitDataKeyFromPKTuple(g Printer, msg ir.MessageSpec, pkTupleExpr string, targetVar string, indent string) {
	if msg.Interleave != nil {
		parentLen := len(msg.Interleave.ParentPKFields)
		g.P(indent, targetVar, " := make(tuple.Tuple, 3+len(", pkTupleExpr, "))")
		g.P(indent, targetVar, "[0] = int64(", msg.Interleave.ParentTypeID, ")")
		g.P(indent, targetVar, "[1] = fdblayer.DataNamespace")
		g.P(indent, "copy(", targetVar, "[2:2+", parentLen, "], ", pkTupleExpr, "[:", parentLen, "])")
		g.P(indent, targetVar, "[2+", parentLen, "] = ", typeIDConstName(msg))
		g.P(indent, "copy(", targetVar, "[3+", parentLen, ":], ", pkTupleExpr, "[", parentLen, ":])")
	} else {
		g.P(indent, targetVar, " := make(tuple.Tuple, 2+len(", pkTupleExpr, "))")
		g.P(indent, targetVar, "[0] = ", typeIDConstName(msg))
		g.P(indent, targetVar, "[1] = fdblayer.DataNamespace")
		g.P(indent, "copy(", targetVar, "[2:], ", pkTupleExpr, ")")
	}
}

func versionstampedPKTupleArgsWithVar(msg ir.MessageSpec, userVersionExpr string) string {
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		if f.IsVersionstamp {
			parts = append(parts, "tuple.IncompleteVersionstamp("+userVersionExpr+")")
		} else {
			parts = append(parts, PackField("entity."+f.GoName, f))
		}
	}
	return strings.Join(parts, ", ")
}

func indexFieldTupleArgs(fields []ir.FieldSpec, varName string) string {
	parts := make([]string, 0, len(fields))
	for _, f := range fields {
		parts = append(parts, PackField(fmt.Sprintf("%s.%s", varName, f.GoName), f))
	}
	return strings.Join(parts, ", ")
}

func fieldParamDecls(fields []ir.FieldSpec) string {
	parts := make([]string, 0, len(fields))
	for _, f := range fields {
		parts = append(parts, f.GoName+" "+FieldGoType(f))
	}
	return strings.Join(parts, ", ")
}

func rangeScanParamDecls(rs ir.IndexRangeScanSpec) string {
	parts := make([]string, 0, len(rs.EqualityFields)+1)
	for _, f := range rs.EqualityFields {
		parts = append(parts, f.GoName+" "+FieldGoType(f))
	}
	parts = append(parts, rs.RangeField.GoName+"Range fdblayer.KeyRange["+FieldGoType(rs.RangeField)+"]")
	return strings.Join(parts, ", ")
}

func emitUnpackTupleElementToField(g Printer, tplElemExpr string, targetFieldExpr string, f ir.FieldSpec, indent string) {
	switch f.Kind {
	case ir.KindString:
		g.P(indent, "if v, ok := ", tplElemExpr, ".(string); ok {")
		g.P(indent, "	", targetFieldExpr, " = v")
		g.P(indent, "}")
	case ir.KindBytes:
		if f.IsVersionstamp {
			g.P(indent, "if v, ok := ", tplElemExpr, ".(tuple.Versionstamp); ok {")
			g.P(indent, "	", targetFieldExpr, " = v.Bytes()")
			g.P(indent, "} else if v, ok := ", tplElemExpr, ".([]byte); ok {")
			g.P(indent, "	", targetFieldExpr, " = v")
			g.P(indent, "}")
		} else {
			g.P(indent, "if v, ok := ", tplElemExpr, ".([]byte); ok {")
			g.P(indent, "	", targetFieldExpr, " = v")
			g.P(indent, "}")
		}
	case ir.KindBool:
		g.P(indent, "if v, ok := ", tplElemExpr, ".(bool); ok {")
		g.P(indent, "	", targetFieldExpr, " = v")
		g.P(indent, "}")
	default:
		if f.IsUnsigned {
			g.P(indent, "if v, ok := ", tplElemExpr, ".(uint64); ok {")
			g.P(indent, "	", targetFieldExpr, " = ", FieldGoType(f), "(v)")
			g.P(indent, "} else if v, ok := ", tplElemExpr, ".(int64); ok {")
			g.P(indent, "	", targetFieldExpr, " = ", FieldGoType(f), "(v)")
			g.P(indent, "}")
		} else {
			g.P(indent, "if v, ok := ", tplElemExpr, ".(int64); ok {")
			g.P(indent, "	", targetFieldExpr, " = ", FieldGoType(f), "(v)")
			g.P(indent, "}")
		}
	}
}

