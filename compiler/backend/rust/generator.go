func generateAtomicMutators(g Printer, msg ir.MessageSpec) {
	snakeMsg := SnakeCase(msg.Name)
	var pkPackArgs []string
	for _, f := range msg.PrimaryKeyFields {
		pkPackArgs = append(pkPackArgs, PackField(FieldIdent(f), f))
	}
	pkArgsStr := strings.Join(pkPackArgs, ", ")

	for _, f := range msg.Fields {
		if f.Mutation == ir.MutationNone {
			continue
		}
		verb := strings.ToLower(MutationEnumVariant(f.Mutation))
		fieldSnake := FieldSnake(f)
		g.P("    pub async fn ", verb, "_", snakeMsg, "_", fieldSnake, "(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        ", fieldRustParamDecls(msg.PrimaryKeyFields), ",")
		g.P("        val: ", FieldRustType(f), ",")
		g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
		g.P(`        let type_id = self.store.get_type_id("`, msg.Name, `")?;`)
		g.P("        let key = dir.pack(&(type_id, fdb_layer::FIELD_NAMESPACE, ", pkArgsStr, ", ", f.Number, "i64));")
		g.P("        let buf = ", encodeAtomicRustExpr("val", f), ".to_le_bytes();")
		g.P("        tr.atomic_op(&key, &buf, fdb_layer::MutationType::", MutationEnumVariant(f.Mutation), ");")
		g.P("        Ok(())")
		g.P("    }")
		g.P()
	}
}

func encodeAtomicRustExpr(expr string, f ir.FieldSpec) string {
	if !f.IsUnsigned && (f.Mutation == ir.MutationMax || f.Mutation == ir.MutationMin) {
		if FieldRustType(f) == "i64" {
			return fmt.Sprintf("((%s as u64) ^ (1u64 << 63))", expr)
		}
		return fmt.Sprintf("((%s as i64 as u64) ^ (1u64 << 63))", expr)
	}
	return fmt.Sprintf("(%s as u64)", expr)
}

func decodeAtomicRustExpr(rawVar string, f ir.FieldSpec) string {
	if !f.IsUnsigned && (f.Mutation == ir.MutationMax || f.Mutation == ir.MutationMin) {
		if FieldRustType(f) == "i64" {
			return fmt.Sprintf("(%s ^ (1u64 << 63)) as i64", rawVar)
		}
		return fmt.Sprintf("((%s ^ (1u64 << 63)) as i64) as %s", rawVar, FieldRustType(f))
	}
	return fmt.Sprintf("%s as %s", rawVar, FieldRustType(f))
}

func generateEncodeWithZeroedAtomics(g Printer, msg ir.MessageSpec, indent string) {
	if ir.HasMutationFields(msg) {
		var nonZeroChecks []string
		for _, f := range msg.Fields {
			if f.Mutation != ir.MutationNone {
				nonZeroChecks = append(nonZeroChecks, fmt.Sprintf("entity.%s != 0", FieldIdent(f)))
			}
		}
		g.P(indent, "let value = if ", strings.Join(nonZeroChecks, " || "), " {")
		g.P(indent, "    let mut clean_entity = entity.clone();")
		for _, f := range msg.Fields {
			if f.Mutation != ir.MutationNone {
				g.P(indent, "    clean_entity.", FieldIdent(f), " = 0;")
			}
		}
		g.P(indent, "    fdb_layer::prost::Message::encode_to_vec(&clean_entity)")
		g.P(indent, "} else {")
		g.P(indent, "    fdb_layer::prost::Message::encode_to_vec(entity)")
		g.P(indent, "};")
	} else {
		g.P(indent, "let value = fdb_layer::prost::Message::encode_to_vec(entity);")
	}
}

func generateUnmarshalAtomicFields(g Printer, msg ir.MessageSpec, sliceExpr string, indent string) {
	for _, f := range msg.Fields {
		if f.Mutation != ir.MutationNone {
			g.P(indent, "entity.", FieldIdent(f), " = 0;")
		}
	}
	g.P(indent, "for fkv in ", sliceExpr, " {")
	g.P(indent, "    if fkv.value().len() < 8 {")
	g.P(indent, "        continue;")
	g.P(indent, "    }")
	g.P(indent, "    let ftpl = match dir.unpack::<Vec<fdb_layer::Element<'_>>>(fkv.key()) {")
	g.P(indent, "        Ok(t) if !t.is_empty() => t,")
	g.P(indent, "        _ => continue,")
	g.P(indent, "    };")
	g.P(indent, "    let field_num = match ftpl.last().and_then(|e| e.as_i64()) {")
	g.P(indent, "        Some(n) => n,")
	g.P(indent, "        None => continue,")
	g.P(indent, "    };")
	g.P(indent, "    let mut raw_bytes = [0u8; 8];")
	g.P(indent, "    raw_bytes.copy_from_slice(&fkv.value()[..8]);")
	g.P(indent, "    let raw_u64 = u64::from_le_bytes(raw_bytes);")
	g.P(indent, "    match field_num {")
	for _, f := range msg.Fields {
		if f.Mutation != ir.MutationNone {
			g.P(indent, "        ", f.Number, " => entity.", FieldIdent(f), " = ", decodeAtomicRustExpr("raw_u64", f), ",")
		}
	}
	g.P(indent, "        _ => {}")
	g.P(indent, "    }")
	g.P(indent, "}")
}

// FieldRustType returns the owned Rust field type emitted by prost for a Protobuf field.
func FieldRustType(f ir.FieldSpec) string {
	switch f.Kind {
	case ir.KindInt32, ir.KindSint32, ir.KindSfixed32, ir.KindEnum:
		return "i32"
	case ir.KindUint32, ir.KindFixed32:
		return "u32"
	case ir.KindInt64, ir.KindSint64, ir.KindSfixed64:
		return "i64"
	case ir.KindUint64, ir.KindFixed64:
		return "u64"
	case ir.KindFloat:
		return "f32"
	case ir.KindDouble:
		return "f64"
	case ir.KindString:
		return "String"
	case ir.KindBool:
		return "bool"
	case ir.KindBytes:
		return "Vec<u8>"
	default:
		return "Vec<u8>"
	}
}

// FieldRustParamType returns the parameter Rust type for method signatures.
func FieldRustParamType(f ir.FieldSpec) string {
	if f.Kind == ir.KindString {
		return "&str"
	}
	if f.Kind == ir.KindBytes {
		return "&[u8]"
	}
	return FieldRustType(f)
}

// PackField normalizes a Rust expression for FDB tuple packing to ensure 100% binary
// compatibility with Go's PackField (signed ints/enums -> i64, unsigned ints -> u64,
// bytes -> fdb_layer::Bytes (0x01 byte string)).
func PackField(expr string, f ir.FieldSpec) string {
	if f.IsUnsigned || f.Kind == ir.KindUint32 || f.Kind == ir.KindFixed32 || f.Kind == ir.KindUint64 || f.Kind == ir.KindFixed64 {
		return fmt.Sprintf("(%s as u64)", expr)
	}
	if f.IsEnum || f.Kind == ir.KindEnum || f.Kind == ir.KindInt32 || f.Kind == ir.KindSint32 || f.Kind == ir.KindSfixed32 || f.Kind == ir.KindInt64 || f.Kind == ir.KindSint64 || f.Kind == ir.KindSfixed64 {
		return fmt.Sprintf("(%s as i64)", expr)
	}
	if f.Kind == ir.KindBytes {
		clean := strings.TrimPrefix(expr, "&")
		return fmt.Sprintf("fdb_layer::Bytes::from(&%s[..])", clean)
	}
	if f.Kind == ir.KindString {
		if strings.HasPrefix(expr, "&") {
			return expr
		}
		return "&" + expr
	}
	return expr
}

// MutationEnumVariant returns the foundationdb::options::MutationType variant name.
func MutationEnumVariant(m ir.MutationType) string {
	switch m {
	case ir.MutationAdd:
		return "Add"
	case ir.MutationMax:
		return "Max"
	case ir.MutationMin:
		return "Min"
	default:
		return "Add"
	}
}

// HasNonRepeatedFields returns true if any field in fields is non-repeated.
func HasNonRepeatedFields(fields []ir.FieldSpec) bool {
	for _, f := range fields {
		if !f.IsRepeated {
			return true
		}
	}
	return false
}

// NonRepeatedFieldsEqual returns a Rust boolean expression comparing all non-repeated fields.
func NonRepeatedFieldsEqual(fields []ir.FieldSpec) string {
	var parts []string
	for _, f := range fields {
		if !f.IsRepeated {
			ident := FieldIdent(f)
			parts = append(parts, fmt.Sprintf("old.%s == entity.%s", ident, ident))
		}
	}
	return strings.Join(parts, " && ")
}

func pkRustTypeExpr(msg ir.MessageSpec) string {
	if len(msg.PrimaryKeyFields) == 1 {
		return FieldRustParamType(msg.PrimaryKeyFields[0])
	}
	if len(msg.PrimaryKeyFields) > 1 {
		return msg.Name + "PrimaryKey"
	}
	return "()"
}

func pkTupleArgsFromEntity(msg ir.MessageSpec, varName string) string {
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		ident := FieldIdent(f)
		parts = append(parts, PackField(fmt.Sprintf("%s.%s", varName, ident), f))
	}
	return strings.Join(parts, ", ")
}

func pkTupleArgsFromParam(msg ir.MessageSpec) string {
	if len(msg.PrimaryKeyFields) == 1 {
		f := msg.PrimaryKeyFields[0]
		if f.Kind == ir.KindString {
			return "pk"
		}
		return PackField("pk", f)
	}
	parts := make([]string, 0, len(msg.PrimaryKeyFields))
	for _, f := range msg.PrimaryKeyFields {
		ident := FieldIdent(f)
		parts = append(parts, PackField("pk."+ident, f))
	}
	return strings.Join(parts, ", ")
}

