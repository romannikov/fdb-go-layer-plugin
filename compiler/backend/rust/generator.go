package rust

import (
	"fmt"
	"strings"
	"unicode"

	"github.com/romannikov/fdb-layer/compiler/ir"
)

// Printer is a minimal line-oriented code emitter (compatible with protogen.GeneratedFile.P).
type Printer interface {
	P(v ...any)
}

// BufferPrinter collects emitted lines into a strings.Builder.
type BufferPrinter struct {
	sb strings.Builder
}

// P writes a line to the buffer.
func (b *BufferPrinter) P(v ...any) {
	for _, x := range v {
		fmt.Fprint(&b.sb, x)
	}
	b.sb.WriteByte('\n')
}

// String returns the accumulated Rust source code.
func (b *BufferPrinter) String() string {
	return b.sb.String()
}

// FieldSnake returns the snake_case field name for a FieldSpec.
func FieldSnake(f ir.FieldSpec) string {
	if f.ProtoName != "" {
		return SnakeCase(f.ProtoName)
	}
	if f.RustName != "" {
		return strings.TrimPrefix(f.RustName, "r#")
	}
	return SnakeCase(f.GoName)
}

// FieldIdent returns the Rust identifier for a FieldSpec (escaping keywords with r#).
func FieldIdent(f ir.FieldSpec) string {
	if f.RustName != "" {
		return f.RustName
	}
	return RustIdent(FieldSnake(f))
}

// GenerateOptions configures Rust code generation.
type GenerateOptions struct {
	GenerateMessages bool
}

// GenerateFile emits the complete Rust repository file (*.fdb.rs) for all annotated
// messages in a Protobuf file.
func GenerateFile(g Printer, sourceName string, messages []ir.MessageSpec) {
	GenerateFileWithOptions(g, sourceName, messages, GenerateOptions{})
}

// GenerateFileWithOptions emits the complete Rust repository file (*.fdb.rs) with configurable options.
func GenerateFileWithOptions(g Printer, sourceName string, messages []ir.MessageSpec, opts GenerateOptions) {
	g.P("// Code generated by protoc-gen-fdb-rust. DO NOT EDIT.")
	g.P("// Source: ", sourceName)
	g.P()
	for i, msg := range messages {
		if i > 0 {
			g.P()
		}
		if opts.GenerateMessages {
			GenerateProstMessage(g, msg)
			g.P()
		}
		GenerateMessage(g, msg)
	}
}

// GenerateProstMessage emits a prost::Message struct definition for msg.
func GenerateProstMessage(g Printer, msg ir.MessageSpec) {
	g.P("#[allow(dead_code, clippy::all)]")
	g.P("#[derive(Clone, PartialEq, ::prost::Message)]")
	g.P("pub struct ", msg.Name, " {")
	for _, f := range msg.Fields {
		g.P("    #[prost(", fieldProstAttr(f), ")]")
		g.P("    pub ", FieldIdent(f), ": ", fieldProstStructType(f), ",")
	}
	g.P("}")
}

func fieldProstAttr(f ir.FieldSpec) string {
	var kindAttr string
	switch f.Kind {
	case ir.KindInt32, ir.KindEnum:
		kindAttr = "int32"
	case ir.KindSint32:
		kindAttr = "sint32"
	case ir.KindSfixed32:
		kindAttr = "sfixed32"
	case ir.KindInt64:
		kindAttr = "int64"
	case ir.KindSint64:
		kindAttr = "sint64"
	case ir.KindSfixed64:
		kindAttr = "sfixed64"
	case ir.KindUint32:
		kindAttr = "uint32"
	case ir.KindFixed32:
		kindAttr = "fixed32"
	case ir.KindUint64:
		kindAttr = "uint64"
	case ir.KindFixed64:
		kindAttr = "fixed64"
	case ir.KindFloat:
		kindAttr = "float"
	case ir.KindDouble:
		kindAttr = "double"
	case ir.KindString:
		kindAttr = "string"
	case ir.KindBool:
		kindAttr = "bool"
	case ir.KindBytes:
		kindAttr = `bytes = "vec"`
	default:
		kindAttr = `bytes = "vec"`
	}
	if f.IsRepeated {
		return fmt.Sprintf(`%s, repeated, tag = "%d"`, kindAttr, f.Number)
	}
	return fmt.Sprintf(`%s, tag = "%d"`, kindAttr, f.Number)
}

func fieldProstStructType(f ir.FieldSpec) string {
	base := FieldRustType(f)
	if f.IsRepeated {
		return fmt.Sprintf("Vec<%s>", base)
	}
	return base
}

// GenerateMessage emits the Rust repository code for a single ir.MessageSpec.
func GenerateMessage(g Printer, msg ir.MessageSpec) {
	if msg.IsQueue {
		generateQueueRepository(g, msg)
	} else {
		generateEntityRepository(g, msg)
	}
}

func generateQueueRepository(g Printer, msg ir.MessageSpec) {
	firstPK := msg.PrimaryKeyFields[0]
	firstPKSnake := FieldIdent(firstPK)
	hasVS := ir.MsgHasVersionstampPK(msg)

	g.P("/// Repository for the `", msg.Name, "` FIFO queue.")
	g.P("#[allow(dead_code, clippy::all)]")
	g.P("#[derive(Clone)]")
	g.P("pub struct ", msg.Name, "Repository {")
	g.P("    store: std::sync::Arc<fdb_layer::RecordStore>,")
	g.P("}")
	g.P()
	g.P("#[allow(dead_code, clippy::all)]")
	g.P("impl ", msg.Name, "Repository {")
	g.P("    pub fn new(store: std::sync::Arc<fdb_layer::RecordStore>) -> Self {")
	g.P("        Self { store }")
	g.P("    }")
	g.P()
	g.P("    /// Enqueues a `", msg.Name, "` into the queue.")
	g.P("    pub async fn enqueue(")
	g.P("        &self,")
	g.P("        tr: &fdb_layer::Transaction,")
	g.P("        dir: &fdb_layer::Subspace,")
	g.P("        entity: &", msg.Name, ",")
	g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
	g.P(`        let type_id = self.store.get_type_id("`, msg.Name, `")?;`)
	if hasVS {
		g.P("        let key = dir.pack_with_versionstamp(&(type_id, fdb_layer::DATA_NAMESPACE, ", versionstampedPKTupleArgs(msg), "));")
	} else {
		g.P("        let key = dir.pack(&(type_id, fdb_layer::DATA_NAMESPACE, ", pkTupleArgsFromEntity(msg, "entity"), "));")
	}
	g.P("        let value = fdb_layer::prost::Message::encode_to_vec(entity);")
	if hasVS {
		g.P("        tr.atomic_op(&key, &value, fdb_layer::MutationType::SetVersionstampedKey);")
	} else {
		g.P("        tr.set(&key, &value);")
	}
	g.P("        Ok(())")
	g.P("    }")
	g.P()
	g.P("    /// Dequeues and removes the single oldest `", msg.Name, "` from the queue.")
	g.P("    pub async fn dequeue(")
	g.P("        &self,")
	g.P("        tr: &fdb_layer::Transaction,")
	g.P("        dir: &fdb_layer::Subspace,")
	g.P("        ", firstPKSnake, ": ", FieldRustParamType(firstPK), ",")
	g.P("    ) -> Result<Option<", msg.Name, ">, fdb_layer::FdbLayerError> {")
	g.P("        use fdb_layer::futures::TryStreamExt;")
	g.P(`        let type_id = self.store.get_type_id("`, msg.Name, `")?;`)
	g.P("        let prefix = dir.pack(&(type_id, fdb_layer::DATA_NAMESPACE, ", PackField(firstPKSnake, firstPK), "));")
	g.P("        let range_opt = fdb_layer::prefix_range_option(&prefix, Some(1));")
	g.P("        let rows: Vec<_> = tr.get_ranges_keyvalues(range_opt, false).try_collect().await?;")
	g.P("        let first_item = match rows.first() {")
	g.P("            Some(item) => item,")
	g.P("            None => return Ok(None),")
	g.P("        };")
	g.P("        let key_to_delete = first_item.key();")
	g.P("        let payload = first_item.value();")
	g.P("        tr.clear(key_to_delete);")
	g.P("        let mut entity = <", msg.Name, " as fdb_layer::prost::Message>::decode(payload)?;")
	if hasVS {
		g.P("        let tpl = dir.unpack::<Vec<fdb_layer::Element<'_>>>(key_to_delete)?;")
		for i, f := range msg.PrimaryKeyFields {
			if f.IsVersionstamp {
				g.P("        if let Some(vs) = tpl.get(", i+2, ").and_then(|e| e.as_versionstamp()) {")
				g.P("            entity.", FieldIdent(f), " = vs.as_bytes().to_vec();")
				g.P("        }")
			}
		}
	}
	g.P("        Ok(Some(entity))")
	g.P("    }")
	g.P("}")
}

func generateEntityRepository(g Printer, msg ir.MessageSpec) {
	pkType := pkRustTypeExpr(msg)

	g.P("#[allow(dead_code)]")
	g.P("pub type ", msg.Name, "PaginationOptions = fdb_layer::PaginationOptions;")
	g.P("#[allow(dead_code)]")
	g.P("pub type ", msg.Name, "PaginatedResult = fdb_layer::PaginatedResult<", msg.Name, ">;")
	g.P()

	if len(msg.PrimaryKeyFields) > 1 {
		g.P("/// Compound primary key for `", msg.Name, "`.")
		g.P("#[allow(dead_code, clippy::all)]")
		g.P("#[derive(Debug, Clone, PartialEq)]")
		g.P("pub struct ", msg.Name, "PrimaryKey {")
		for _, f := range msg.PrimaryKeyFields {
			g.P("    pub ", FieldIdent(f), ": ", FieldRustType(f), ",")
		}
		g.P("}")
		g.P()
	}

	g.P("/// Repository for `", msg.Name, "` entities.")
	g.P("#[allow(dead_code, clippy::all)]")
	g.P("#[derive(Clone)]")
	g.P("pub struct ", msg.Name, "Repository {")
	g.P("    store: std::sync::Arc<fdb_layer::RecordStore>,")
	g.P("}")
	g.P()
	g.P("#[allow(dead_code, clippy::all)]")
	g.P("impl ", msg.Name, "Repository {")
	g.P("    pub fn new(store: std::sync::Arc<fdb_layer::RecordStore>) -> Self {")
	g.P("        Self { store }")
	g.P("    }")
	g.P()

	generateCreate(g, msg)
	generateGet(g, msg)
	generateSet(g, msg)
	generateDelete(g, msg)
	generateBatchGet(g, msg)
	generateList(g, msg)
	for _, idx := range msg.SecondaryIndexes {
		generateGetByIndex(g, msg, idx)
	}
	generateAtomicMutators(g, msg)

	g.P("}")
	g.P()

	if len(msg.PrimaryKeyFields) == 1 && (msg.PrimaryKeyFields[0].Kind == ir.KindString || msg.PrimaryKeyFields[0].Kind == ir.KindBytes) {
		ownedPK := FieldRustType(msg.PrimaryKeyFields[0])
		g.P("#[fdb_layer::async_trait]")
		g.P("impl fdb_layer::GenericRepository<", msg.Name, ", ", ownedPK, "> for ", msg.Name, "Repository {")
		g.P("    async fn create(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        entity: &", msg.Name, ",")
		g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
		g.P("        Self::create(self, tr, dir, entity).await")
		g.P("    }")
		g.P()
		g.P("    async fn get(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        pk: ", ownedPK, ",")
		g.P("    ) -> Result<", msg.Name, ", fdb_layer::FdbLayerError> {")
		g.P("        Self::get(self, tr, dir, &pk).await")
		g.P("    }")
		g.P()
		g.P("    async fn set(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        entity: &", msg.Name, ",")
		g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
		g.P("        Self::set(self, tr, dir, entity).await")
		g.P("    }")
		g.P()
		g.P("    async fn delete(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        pk: ", ownedPK, ",")
		g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
		g.P("        Self::delete(self, tr, dir, &pk).await")
		g.P("    }")
		g.P("}")
	} else {
		g.P("#[fdb_layer::async_trait]")
		g.P("impl fdb_layer::GenericRepository<", msg.Name, ", ", pkType, "> for ", msg.Name, "Repository {")
		g.P("    async fn create(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        entity: &", msg.Name, ",")
		g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
		g.P("        Self::create(self, tr, dir, entity).await")
		g.P("    }")
		g.P()
		g.P("    async fn get(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        pk: ", pkType, ",")
		g.P("    ) -> Result<", msg.Name, ", fdb_layer::FdbLayerError> {")
		g.P("        Self::get(self, tr, dir, pk).await")
		g.P("    }")
		g.P()
		g.P("    async fn set(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        entity: &", msg.Name, ",")
		g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
		g.P("        Self::set(self, tr, dir, entity).await")
		g.P("    }")
		g.P()
		g.P("    async fn delete(")
		g.P("        &self,")
		g.P("        tr: &fdb_layer::Transaction,")
		g.P("        dir: &fdb_layer::Subspace,")
		g.P("        pk: ", pkType, ",")
		g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
		g.P("        Self::delete(self, tr, dir, pk).await")
		g.P("    }")
		g.P("}")
	}
}

func generateCreate(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	hasVS := ir.MsgHasVersionstampPK(msg)
	hasMut := ir.HasMutationFields(msg)
	pkArgs := pkTupleArgsFromEntity(msg, "entity")

	g.P("    pub async fn create(")
	g.P("        &self,")
	g.P("        tr: &fdb_layer::Transaction,")
	g.P("        dir: &fdb_layer::Subspace,")
	g.P("        entity: &", msg.Name, ",")
	g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
	g.P(`        let type_id = self.store.get_type_id("`, msg.Name, `")?;`)
	if hasVS {
		g.P("        let key = dir.pack_with_versionstamp(&(type_id, fdb_layer::DATA_NAMESPACE, ", versionstampedPKTupleArgs(msg), "));")
	} else {
		g.P("        let key = dir.pack(&(type_id, fdb_layer::DATA_NAMESPACE, ", pkArgs, "));")
		g.P("        if tr.get(&key, false).await?.is_some() {")
		g.P(`            return Err(fdb_layer::FdbLayerError::AlreadyExists("`, lowerName, `"));`)
		g.P("        }")
	}

	generateEncodeWithZeroedAtomics(g, msg, "        ")

	if hasVS {
		g.P("        tr.atomic_op(&key, &value, fdb_layer::MutationType::SetVersionstampedKey);")
	} else {
		g.P("        tr.set(&key, &value);")
	}

	if hasMut {
		for _, f := range msg.Fields {
			if f.Mutation != ir.MutationNone {
				ident := FieldIdent(f)
				g.P("        if entity.", ident, " != 0 {")
				g.P("            let field_key = dir.pack(&(type_id, fdb_layer::FIELD_NAMESPACE, ", pkArgs, ", ", f.Number, "i64));")
				g.P("            let buf = ", encodeAtomicRustExpr("entity."+ident, f), ".to_le_bytes();")
				g.P("            tr.atomic_op(&field_key, &buf, fdb_layer::MutationType::", MutationEnumVariant(f.Mutation), ");")
				g.P("        }")
			}
		}
	}

	for _, idx := range msg.SecondaryIndexes {
		if idx.IsFanOut {
			for i, f := range idx.Fields {
				if f.IsRepeated {
					g.P("        for item in &entity.", FieldIdent(f), " {")
					emitFanOutIndexWrite(g, msg, idx, i, "entity", true, "            ")
					g.P("        }")
				}
			}
		} else {
			g.P("        tr.set(&dir.pack(&(type_id, fdb_layer::INDEX_NAMESPACE, ", idx.IndexID, "i64, ", indexFieldTupleArgs(idx.Fields, "entity"), ", ", pkArgs, ")), &[]);")
		}
	}

	g.P("        Ok(())")
	g.P("    }")
	g.P()
}

func generateGet(g Printer, msg ir.MessageSpec) {
	lowerName := strings.ToLower(msg.Name)
	pkType := pkRustTypeExpr(msg)
	pkArgs := pkTupleArgsFromParam(msg)
	hasMut := ir.HasMutationFields(msg)

	g.P("    pub async fn get(")
	g.P("        &self,")
	g.P("        tr: &fdb_layer::Transaction,")
	g.P("        dir: &fdb_layer::Subspace,")
	g.P("        pk: ", pkType, ",")
	g.P("    ) -> Result<", msg.Name, ", fdb_layer::FdbLayerError> {")
	if hasMut {
		g.P("        use fdb_layer::futures::TryStreamExt;")
	}
	g.P(`        let type_id = self.store.get_type_id("`, msg.Name, `")?;`)
	g.P("        let key = dir.pack(&(type_id, fdb_layer::DATA_NAMESPACE, ", pkArgs, "));")
	if hasMut {
		g.P("        let field_prefix = dir.pack(&(type_id, fdb_layer::FIELD_NAMESPACE, ", pkArgs, "));")
		g.P("        let field_range = fdb_layer::prefix_range_option(&field_prefix, None);")
		g.P("        let val_fut = tr.get(&key, false);")
		g.P("        let field_fut = tr.get_ranges_keyvalues(field_range, false).try_collect::<Vec<_>>();")
		g.P("        let (value_opt, field_kvs) = fdb_layer::futures::future::try_join(val_fut, field_fut).await?;")
	} else {
		g.P("        let value_opt = tr.get(&key, false).await?;")
	}
	g.P("        let value = value_opt.ok_or(fdb_layer::FdbLayerError::NotFound(\"", lowerName, "\"))?;")
	if hasMut {
		g.P("        let mut entity = <", msg.Name, " as fdb_layer::prost::Message>::decode(value.as_ref())?;")
		generateUnmarshalAtomicFields(g, msg, "&field_kvs", "        ")
	} else {
		g.P("        let entity = <", msg.Name, " as fdb_layer::prost::Message>::decode(value.as_ref())?;")
	}
	g.P("        Ok(entity)")
	g.P("    }")
	g.P()
}

func generateSet(g Printer, msg ir.MessageSpec) {
	hasVS := ir.MsgHasVersionstampPK(msg)
	pkArgsEntity := pkTupleArgsFromEntity(msg, "entity")
	pkArgsOld := pkTupleArgsFromEntity(msg, "old")

	g.P("    pub async fn set(")
	g.P("        &self,")
	g.P("        tr: &fdb_layer::Transaction,")
	g.P("        dir: &fdb_layer::Subspace,")
	g.P("        entity: &", msg.Name, ",")
	g.P("    ) -> Result<(), fdb_layer::FdbLayerError> {")
	g.P(`        let type_id = self.store.get_type_id("`, msg.Name, `")?;`)

	if len(msg.SecondaryIndexes) > 0 {
		g.P("        let mut old: Option<", msg.Name, "> = None;")
	}

	if hasVS {
		var vsFieldIdent string
		for _, f := range msg.PrimaryKeyFields {
			if f.IsVersionstamp {
				vsFieldIdent = FieldIdent(f)
				break
			}
		}
		g.P("        if entity.", vsFieldIdent, ".iter().any(|&b| b != 0) {")
		g.P("            let old_key = dir.pack(&(type_id, fdb_layer::DATA_NAMESPACE, ", pkArgsEntity, "));")
		g.P("            tr.clear(&old_key);")
		g.P("        }")
		g.P("        let key = dir.pack_with_versionstamp(&(type_id, fdb_layer::DATA_NAMESPACE, ", versionstampedPKTupleArgs(msg), "));")
	} else {
		g.P("        let key = dir.pack(&(type_id, fdb_layer::DATA_NAMESPACE, ", pkArgsEntity, "));")
		if len(msg.SecondaryIndexes) > 0 {
			g.P("        if let Some(old_val) = tr.get(&key, false).await? {")
			g.P("            old = Some(<", msg.Name, " as fdb_layer::prost::Message>::decode(old_val.as_ref())?);")
			g.P("        }")
		}
	}

	generateEncodeWithZeroedAtomics(g, msg, "        ")

	if hasVS {
		g.P("        tr.atomic_op(&key, &value, fdb_layer::MutationType::SetVersionstampedKey);")
	} else {
		g.P("        tr.set(&key, &value);")
	}

	for _, idx := range msg.SecondaryIndexes {
		if idx.IsFanOut {
			for i, f := range idx.Fields {
				if f.IsRepeated {
					ident := FieldIdent(f)
					g.P("        if let Some(ref old) = old {")
					if HasNonRepeatedFields(idx.Fields) {
						g.P("            if ", NonRepeatedFieldsEqual(idx.Fields), " {")
						g.P("                let old_set: std::collections::HashSet<_> = old.", ident, ".iter().collect();")
						g.P("                let new_set: std::collections::HashSet<_> = entity.", ident, ".iter().collect();")
						g.P("                for item in &old.", ident, " {")
						g.P("                    if !new_set.contains(item) {")
						emitFanOutIndexWrite(g, msg, idx, i, "old", false, "                        ")
						g.P("                    }")
						g.P("                }")
						g.P("                for item in &entity.", ident, " {")
						g.P("                    if !old_set.contains(item) {")
						emitFanOutIndexWrite(g, msg, idx, i, "entity", true, "                        ")
						g.P("                    }")
						g.P("                }")
						g.P("            } else {")
						g.P("                for item in &old.", ident, " {")
						emitFanOutIndexWrite(g, msg, idx, i, "old", false, "                    ")
						g.P("                }")
						g.P("                for item in &entity.", ident, " {")
						emitFanOutIndexWrite(g, msg, idx, i, "entity", true, "                    ")
						g.P("                }")
						g.P("            }")
					} else {
						g.P("            let old_set: std::collections::HashSet<_> = old.", ident, ".iter().collect();")
						g.P("            let new_set: std::collections::HashSet<_> = entity.", ident, ".iter().collect();")
						g.P("            for item in &old.", ident, " {")
						g.P("                if !new_set.contains(item) {")
						emitFanOutIndexWrite(g, msg, idx, i, "old", false, "                    ")
						g.P("                }")
						g.P("            }")
						g.P("            for item in &entity.", ident, " {")
						g.P("                if !old_set.contains(item) {")
						emitFanOutIndexWrite(g, msg, idx, i, "entity", true, "                    ")
						g.P("                }")
						g.P("            }")
					}
					g.P("        } else {")
					g.P("            for item in &entity.", ident, " {")
					emitFanOutIndexWrite(g, msg, idx, i, "entity", true, "                ")
					g.P("            }")
					g.P("        }")
				}
			}
		} else {
			var diffParts []string
			for _, f := range idx.Fields {
				ident := FieldIdent(f)
				diffParts = append(diffParts, fmt.Sprintf("old.%s != entity.%s", ident, ident))
			}
			g.P("        let idx_changed = match old {")
			g.P("            Some(ref old) => ", strings.Join(diffParts, " || "), ",")
			g.P("            None => true,")
			g.P("        };")
			g.P("        if idx_changed {")
			g.P("            if let Some(ref old) = old {")
			g.P("                tr.clear(&dir.pack(&(type_id, fdb_layer::INDEX_NAMESPACE, ", idx.IndexID, "i64, ", indexFieldTupleArgs(idx.Fields, "old"), ", ", pkArgsOld, ")));")
			g.P("            }")
			g.P("            tr.set(&dir.pack(&(type_id, fdb_layer::INDEX_NAMESPACE, ", idx.IndexID, "i64, ", indexFieldTupleArgs(idx.Fields, "entity"), ", ", pkArgsEntity, ")), &[]);")
			g.P("        }")
		}
	}

	g.P("        Ok(())")
	g.P("    }")
	g.P()
}

