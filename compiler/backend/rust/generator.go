func emitFanOutIndexWrite(g Printer, msg ir.MessageSpec, idx ir.SecondaryIndexSpec, repeatedIdx int, varName string, isSet bool, indent string) {
	var args []string
	args = append(args, "type_id", "fdb_layer::INDEX_NAMESPACE", fmt.Sprintf("%di64", idx.IndexID))
	for j, sf := range idx.Fields {
		if j == repeatedIdx {
			if sf.Kind == ir.KindString {
				args = append(args, "item")
			} else if sf.Kind == ir.KindBytes {
				args = append(args, PackField("item", sf))
			} else {
				args = append(args, PackField("*item", sf))
			}
		} else {
			ident := FieldIdent(sf)
			args = append(args, PackField(varName+"."+ident, sf))
		}
	}
	for _, pkf := range msg.PrimaryKeyFields {
		ident := FieldIdent(pkf)
		args = append(args, PackField(varName+"."+ident, pkf))
	}
	tupleExpr := strings.Join(args, ", ")
	if isSet {
		g.P(indent, "tr.set(&dir.pack(&(", tupleExpr, ")), &[]);")
	} else {
		g.P(indent, "tr.clear(&dir.pack(&(", tupleExpr, ")));")
	}
}

// JoinFieldNamesSnake joins field names in snake_case with "_and_".
func JoinFieldNamesSnake(fields []ir.FieldSpec) string {
	names := make([]string, 0, len(fields))
	for _, f := range fields {
		names = append(names, FieldSnake(f))
	}
	return strings.Join(names, "_and_")
}

// SnakeCase converts a CamelCase or snake_case identifier into snake_case.
func SnakeCase(s string) string {
	if s == "" {
		return ""
	}
	var out strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if unicode.IsUpper(r) {
			if i > 0 && runes[i-1] != '_' && (unicode.IsLower(runes[i-1]) || (i+1 < len(runes) && unicode.IsLower(runes[i+1]))) {
				out.WriteByte('_')
			}
			out.WriteRune(unicode.ToLower(r))
		} else {
			out.WriteRune(r)
		}
	}
	return out.String()
}

